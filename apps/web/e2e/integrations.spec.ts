/* Use case: Verifies usable scoped keys and real private iframe delivery.
What it does: Covers owner controls, exact chart/table evidence, origin/source checks, one-use exchange, revocation and responsive layouts without external services. */

import { execFileSync } from "node:child_process";
import { randomUUID } from "node:crypto";
import { mkdirSync, mkdtempSync, readFileSync, rmSync } from "node:fs";
import https from "node:https";
import { tmpdir } from "node:os";
import { join } from "node:path";
import { expect, test } from "@playwright/test";
import { finishInitialReview } from "./workspace-helpers";

const api = "http://127.0.0.1:8001";
const web = "http://127.0.0.1:3001";

test("owner keys and private embedded dashboards retain exact access and reject another host", async ({ page, browser }) => {
  test.setTimeout(120_000);
  page.setDefaultTimeout(20_000);
  const errors: string[] = [];
  page.on("pageerror", error => errors.push(error.message));
  page.on("console", event => { if (event.text().includes("same key")) errors.push(event.text()); });
  const tlsDirectory = mkdtempSync(join(tmpdir(), "execplus-embed-fixture-"));
  execFileSync("openssl", ["req", "-x509", "-newkey", "rsa:2048", "-nodes", "-keyout", join(tlsDirectory, "key.pem"), "-out", join(tlsDirectory, "cert.pem"), "-days", "1", "-subj", "/CN=approved.localhost", "-addext", "subjectAltName=DNS:approved.localhost,DNS:wrong.localhost"], { stdio: "ignore" });
  let fixtureHtml = "";
  const hostServer = https.createServer({ key: readFileSync(join(tlsDirectory, "key.pem")), cert: readFileSync(join(tlsDirectory, "cert.pem")) }, (_, response) => { response.writeHead(200, { "Content-Type": "text/html", "Cache-Control": "no-store" }); response.end(fixtureHtml); });
  await new Promise<void>(resolve => hostServer.listen(0, "127.0.0.1", resolve));
  const address = hostServer.address();
  if (!address || typeof address === "string") throw new Error("Local TLS fixture has no port");
  const host = `https://approved.localhost:${address.port}`;
  const wrongHost = `https://wrong.localhost:${address.port}`;
  try {
  const token = execFileSync("python3", ["-m", "execplus.manage", "provision-user", "--email", `integrations-${randomUUID()}@example.test`], { cwd: "../..", encoding: "utf8" }).trim();
  const headers = { Authorization: `Bearer ${token}` };
  await page.goto("/workspace");
  await page.getByLabel("Session token").fill(token);
  await page.getByRole("button", { name: "Sign in", exact: true }).click();
  await page.getByLabel("CSV or Excel file").setInputFiles({ name: "private-dashboard.csv", mimeType: "text/csv", buffer: Buffer.from("region,amount\nNorth,9007199254740993.000001\nSouth,-0.20\nMissing,\nZero,0\n") });
  await page.getByRole("button", { name: "Upload file", exact: true }).click();
  await finishInitialReview(page);
  const wid = await page.getByLabel("Current workspace").inputValue();
  const did = await page.getByLabel("Dataset", { exact: true }).inputValue();
  const uid = await page.getByLabel("Profile upload").inputValue();
  const base = `/workspaces/${wid}`;
  const root = `${base}/datasets/${did}/uploads/${uid}`;
  const before = await (await page.request.get(api + root + "/understanding", { headers })).json();
  const confirmed = await page.request.post(api + root + "/understanding", { headers, data: { revision_id: before.revision_id, expected_version: before.version, state: "confirmed", definition: { ...before.definition, grain: "record", columns: before.definition.columns.map((column: { name: string }) => ({ ...column, meaning: `Recorded ${column.name}`, unit: column.name === "amount" ? "USD" : "" })) } } });
  expect(confirmed.status()).toBe(201);
  const views = await (await page.request.get(api + root + "/adaptive-views", { headers })).json();
  const studyResponse = await page.request.post(api + root + "/studies", { headers, data: { name: "Exact regional totals", question: "What is the total amount in each region?", revision_id: views.revision_id, understanding_id: views.understanding_id, method: { kind: "metric", column: "amount", aggregation: "sum", group_by: ["region"] } } });
  expect(studyResponse.status()).toBe(201);
  const study = await studyResponse.json();
  expect((await page.request.patch(`${api}${base}/studies/${study.study.id}`, { headers, data: { shared: true } })).status()).toBe(204);
  const boardResponse = await page.request.post(`${api}${base}/study-boards`, { headers, data: { name: "Private regional dashboard", shared: true, pins: [study.version.id] } });
  expect(boardResponse.status()).toBe(201);
  const board = await boardResponse.json();
  await page.getByRole("navigation", { name: "Workspace navigation" }).getByRole("button", { name: "Team & settings", exact: true }).click();
  const panel = page.getByRole("region", { name: "Private integrations" });
  await expect(panel.getByRole("heading", { name: "A key for one dataset" })).toBeVisible();
  await expect(panel).toContainText("They cannot act as another member.");
  await panel.getByLabel("Key name").fill("Browser fixture key");
  await panel.getByLabel("Integration dataset").selectOption(did);
  await panel.getByLabel("Read allowed rows", { exact: true }).check();
  await panel.getByRole("button", { name: "Create read-only key" }).click();
  const secretInput = panel.getByLabel("New read-only API key", { exact: true });
  await expect(secretInput).toBeVisible();
  const key = await secretInput.inputValue();
  const keys = await (await page.request.get(`${api}${base}/integrations/keys`, { headers })).json();
  const issuer = await (await page.request.get(`${api}/auth/me`, { headers })).json();
  expect(keys[0].user_id).toBe(issuer.id);
  const keyHeaders = { Authorization: `Bearer ${key}` };
  const rows = await page.request.post(`${api}/integration/v1${root}/rows`, { headers: keyHeaders, data: {} });
  expect(rows.ok()).toBe(true);
  expect(await rows.text()).toContain("9007199254740993.000001");
  expect((await page.request.get(`${api}/workspaces`, { headers: keyHeaders })).status()).toBe(401);
  await panel.getByRole("button", { name: "I saved it — hide secret" }).click();
  await expect(secretInput).toHaveCount(0);
  const output = "../../data/verification/2026-10-16/remaining-work/integrations-browser";
  mkdirSync(output, { recursive: true });
  await page.emulateMedia({ reducedMotion: "reduce" });
  for (const width of [1440, 390, 320]) {
    await page.setViewportSize({ width, height: 1000 });
    await panel.scrollIntoViewIfNeeded();
    expect(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth + 1)).toBe(true);
    await panel.screenshot({ path: `${output}/keys-${width}.png` });
  }
  await panel.getByRole("button", { name: "Revoke key", exact: true }).click();
  await expect(panel.getByText("Revoked", { exact: true })).toBeVisible();
  expect((await page.request.post(`${api}/integration/v1${root}/rows`, { headers: keyHeaders, data: {} })).status()).toBe(404);
  expect(keys).toHaveLength(1);
  await panel.getByRole("button", { name: "Notifications", exact: true }).click();
  await expect(panel).toContainText("An operator must configure an approved receiver");
  await panel.getByRole("button", { name: "Embed a dashboard", exact: true }).click();
  await panel.getByLabel("Shared dashboard").selectOption(board.id);
  await panel.getByLabel("Approved host origin").fill(host);
  await panel.getByRole("button", { name: "Create private embed" }).click();
  const code = await panel.getByLabel("One-use private embed code", { exact: true }).inputValue();
  const grant = code.match(/\/embed\/([a-f0-9-]{36})/)?.[1];
  const secret = code.match(/epb_[A-Za-z0-9_-]{43}/)?.[0];
  expect(grant).toBeTruthy(); expect(secret).toBeTruthy();
  await panel.getByRole("button", { name: "I saved it — hide secret" }).click();
  const embeddedContext = await browser.newContext({ reducedMotion: "reduce", ignoreHTTPSErrors: true });
  const embedded = await embeddedContext.newPage();
  embedded.on("pageerror", error => errors.push(error.message));
  fixtureHtml = `<html><body style="margin:0"><iframe id="view" title="Private view" src="${web}/embed/${grant}" style="width:100%;height:100vh;border:0"></iframe></body></html>`;
  const frameResponse = embedded.waitForResponse(response => response.url() === `${web}/embed/${grant}` && response.request().resourceType() === "document", { timeout: 20_000 });
  await embedded.goto(`${host}/dashboard`);
  expect((await frameResponse).headers()["content-security-policy"]).toContain(`frame-ancestors ${host}`);
  const frame = embedded.frameLocator("iframe");
  await expect(frame.getByText("Waiting for the approved host", { exact: false })).toBeVisible();
  await embedded.locator("iframe").contentFrame().getByRole("main").evaluate((_, value) => window.postMessage(value, window.location.origin), { type: "execplus:open", grantId: grant, secret });
  await expect(frame.getByText("Waiting for the approved host", { exact: false })).toBeVisible();
  await embedded.evaluate(({ grant, secret, web }) => { const element = document.querySelector("iframe")!; element.contentWindow!.postMessage({ type: "execplus:open", grantId: grant, secret }, web); }, { grant, secret, web });
  await expect(frame.getByRole("heading", { name: "Private regional dashboard", exact: true })).toBeVisible();
  const exactView = frame.locator('[data-visualization="Exact regional totals"]').first();
  await expect(exactView.locator('[data-chart-renderer="apache-echarts"]')).toHaveAttribute("data-engine-ready", "true");
  await expect(exactView).not.toContainText("__value");
  await expect(exactView).toContainText("amount · USD");
  expect(await frame.getByRole("main").evaluate(element => getComputedStyle(element).fontFamily.toLowerCase())).toContain("manrope");
  await exactView.getByRole("button", { name: "Table", exact: true }).click();
  await expect(exactView).toContainText("9007199254740993.000001");
  await expect(exactView).toContainText("-0.200000000000");
  await expect(exactView).toContainText("Missing");
  await exactView.getByRole("button", { name: "Chart", exact: true }).click();
  const evidenceDisclosure = frame.locator("details").filter({ has: frame.locator("summary", { hasText: "Exact calculation evidence" }) });
  await evidenceDisclosure.locator("summary").click();
  await expect(evidenceDisclosure.locator("pre")).toContainText("\"__value\"");
  await expect(evidenceDisclosure.locator("pre")).toContainText("9007199254740993.000001");
  await evidenceDisclosure.locator("summary").click();
  for (const width of [1440, 390, 320]) {
    await embedded.setViewportSize({ width, height: 1000 });
    await frame.getByRole("main").evaluate(() => window.scrollTo(0, 0));
    expect(await frame.getByRole("main").evaluate(() => document.documentElement.scrollWidth <= innerWidth + 1)).toBe(true);
    await embedded.screenshot({ path: `${output}/embed-${width}.png` });
  }
  expect(await embedded.evaluate(() => localStorage.length + sessionStorage.length)).toBe(0);
  expect(await frame.getByRole("main").evaluate(() => localStorage.length + sessionStorage.length)).toBe(0);
  const wrong = await embeddedContext.newPage();
  const framingErrors: string[] = [];
  wrong.on("console", event => { if (event.type() === "error") framingErrors.push(event.text()); });
  await wrong.goto(`${wrongHost}/dashboard`);
  await expect.poll(() => framingErrors.some(value => value.includes("frame-ancestors"))).toBe(true);
  await expect(wrong.frameLocator("iframe").getByRole("heading", { name: "Private regional dashboard" })).toHaveCount(0);
  await wrong.close();
  await panel.getByRole("button", { name: "Revoke embedded view", exact: true }).click();
  await frame.getByRole("button", { name: "Refresh access & results" }).click();
  await expect(frame.getByText("This private view is no longer available.", { exact: false })).toBeVisible();
  await expect(frame.getByRole("heading", { name: "Exact regional totals", exact: true })).toHaveCount(0);
  expect((await page.request.get(`${api}/embed/${grant}/descriptor`)).status()).toBe(404);
  expect(errors).toEqual([]);
  await embeddedContext.close();
  } finally {
    hostServer.closeAllConnections();
    await new Promise<void>(resolve => hostServer.close(() => resolve()));
    rmSync(tlsDirectory, { recursive: true, force: true });
  }
});
