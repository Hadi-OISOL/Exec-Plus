/* Use case: Verifies explicit owner-managed dataset access in the real browser.
What it does: Checks unsaved drafts, scoped member visibility, conflict recovery and owner self-denial recovery. */

import { execFileSync } from "node:child_process";
import { randomUUID } from "node:crypto";
import { mkdirSync } from "node:fs";
import { expect, test } from "@playwright/test";
import { finishInitialReview } from "./workspace-helpers";

const api = "http://127.0.0.1:8001";

test("owner saves row and field rules, retains failed drafts and can recover self-denial", async ({ page, browser }) => {
  test.setTimeout(180_000);
  const errors: string[] = [];
  page.on("pageerror", error => errors.push(error.message));
  const provision = (email: string) => execFileSync("python3", ["-m", "execplus.manage", "provision-user", "--email", email], { cwd: "../..", encoding: "utf8" }).trim();
  const ownerToken = provision(`access-owner-${randomUUID()}@example.test`);
  const memberEmail = `access-member-${randomUUID()}@example.test`;
  const memberToken = provision(memberEmail);
  const owner = { Authorization: `Bearer ${ownerToken}` };
  const member = { Authorization: `Bearer ${memberToken}` };
  await page.goto("/workspace");
  await page.getByLabel("Session token").fill(ownerToken);
  await page.getByRole("button", { name: "Sign in", exact: true }).click();
  await page.getByLabel("CSV or Excel file").setInputFiles({ name: "regional-access.csv", mimeType: "text/csv", buffer: Buffer.from("region,revenue,private_note\nNorth,100,hidden one\nSouth,900,hidden two\nNorth,200,hidden three\n") });
  await page.getByRole("button", { name: "Upload file", exact: true }).click();
  await finishInitialReview(page);
  const wid = await page.getByLabel("Current workspace").inputValue();
  const did = await page.getByLabel("Dataset", { exact: true }).inputValue();
  const upload = await page.getByLabel("Profile upload").inputValue();
  const base = `${api}/workspaces/${wid}`;
  const path = `${base}/datasets/${did}/access-policy`;
  const meaningPath = `${base}/datasets/${did}/uploads/${upload}/understanding`;
  const meaning = await (await page.request.get(meaningPath, { headers: owner })).json();
  expect((await page.request.post(meaningPath, { headers: owner, data: { revision_id: meaning.revision_id, expected_version: meaning.version, state: "confirmed", definition: { ...meaning.definition, grain: "record", columns: meaning.definition.columns.map((column: { name: string; role: string }) => ({ ...column, meaning: `Declared ${column.name}`, unit: column.role === "metric" ? "USD" : "" })) } } })).ok()).toBe(true);
  const invite = await page.request.post(`${base}/invitations`, { headers: owner, data: { email: memberEmail, role: "member" } });
  expect(invite.status()).toBe(201);
  expect((await page.request.post(`${base}/invitations/${(await invite.json()).id}/accept`, { headers: member })).ok()).toBe(true);
  await page.getByRole("navigation", { name: "Workspace navigation" }).getByRole("button", { name: "Team & settings", exact: true }).click();
  const panel = page.getByRole("region", { name: "Dataset access settings", exact: true });
  await panel.getByLabel("Dataset to manage").selectOption(did);
  await panel.getByRole("radio", { name: "Choose each person’s access", exact: false }).check();
  const policy = await (await page.request.get(path, { headers: owner })).json();
  const people = policy.members as { user_id: string; role: string; display_name: string }[];
  const teammate = people.find(person => person.role === "member")!;
  expect(teammate).toBeTruthy();
  await panel.getByLabel("Person to add").selectOption(teammate.user_id);
  await panel.getByRole("button", { name: "Add person", exact: true }).click();
  await panel.getByRole("checkbox", { name: "All fields, including future fields", exact: true }).uncheck();
  await panel.getByRole("checkbox", { name: "private_note", exact: true }).uncheck();
  await panel.getByRole("button", { name: "Add row condition", exact: true }).click();
  const condition = panel.getByRole("group", { name: `Row condition 1 for ${teammate.display_name}`, exact: true });
  await condition.getByRole("combobox", { name: "Field", exact: true }).selectOption("region");
  await condition.getByLabel("Value", { exact: true }).fill("North");
  expect((await (await page.request.get(path, { headers: owner })).json()).version).toBe(0);
  let rejectSave = true;
  await page.route("**/access-policy", route => route.request().method() === "PUT" && rejectSave
    ? route.fulfill({ status: 503, json: { error: { message: "Temporary save failure" } } }) : route.continue());
  await panel.getByRole("button", { name: "Save access rules", exact: true }).click();
  await expect(panel.getByRole("alert")).toContainText("Temporary save failure");
  await expect(condition.getByLabel("Value", { exact: true })).toHaveValue("North");
  rejectSave = false;
  await panel.getByRole("button", { name: "Save access rules", exact: true }).click();
  await expect(panel.getByRole("status")).toContainText("Access saved");
  const saved = await (await page.request.get(path, { headers: owner })).json();
  expect(saved).toMatchObject({ version: 1, enabled: true, grants: [{ user_id: teammate.user_id, columns: ["region", "revenue"], conditions: [{ column: "region", operator: "eq", value: "North" }] }] });
  const profilePath = `${base}/datasets/${did}/uploads/${upload}/profile`;
  expect((await page.request.get(profilePath, { headers: owner })).status()).toBe(404);
  const visible = await page.request.get(profilePath, { headers: member });
  expect(visible.ok()).toBe(true);
  const projected = await visible.json();
  expect(projected.profile.row_count).toBe(2);
  expect(projected.profile.columns.map((column: { name: string }) => column.name)).toEqual(["region", "revenue"]);
  expect(JSON.stringify(projected)).not.toContain("private_note");
  const records = await page.request.post(`${base}/datasets/${did}/uploads/${upload}/rows`, { headers: member, data: { limit: 10 } });
  expect(records.ok()).toBe(true);
  const table = await records.json();
  expect(table.columns).toEqual(["region", "revenue"]);
  expect(table.rows.map((row: unknown[]) => row.map(String))).toEqual([["North", "100"], ["North", "200"]]);
  expect(JSON.stringify(table)).not.toContain("private_note");
  expect(JSON.stringify(table)).not.toContain("South");
  expect((await page.request.get(`${base}/dataset-access`, { headers: member })).status()).toBe(403);
  const memberContext = await browser.newContext();
  const memberPage = await memberContext.newPage();
  memberPage.on("pageerror", error => errors.push(error.message));
  await memberPage.goto(`http://127.0.0.1:3001/workspace?workspace=${wid}`);
  await memberPage.getByLabel("Session token").fill(memberToken);
  await memberPage.getByRole("button", { name: "Sign in", exact: true }).click();
  await expect(memberPage.getByRole("region", { name: "Analytics home", exact: true })).toBeVisible();
  await expect(memberPage.getByRole("complementary", { name: "Your dataset access", exact: true })).toContainText("rows and fields shared with you");
  await expect(memberPage.getByRole("button", { name: "Skip for now", exact: true })).toHaveCount(0);
  await memberPage.getByRole("navigation", { name: "Workspace navigation" }).getByRole("button", { name: "Ask Syntelio", exact: true }).click();
  await memberPage.getByLabel("Your question", { exact: true }).fill("Make a diagram of how our data converge");
  await memberPage.getByRole("button", { name: "Ask", exact: true }).click();
  const answer = memberPage.locator(".conversationTurn").last();
  await expect(answer.getByRole("region", { name: "Data organisation diagram", exact: true })).toBeVisible();
  await expect(answer).toContainText("2 of 2 fields included");
  await expect(answer).toContainText("revenue");
  await expect(answer).not.toContainText("South");
  await expect(answer).not.toContainText("private_note");
  await expect(answer).not.toContainText("hidden one");
  await memberContext.close();
  await page.reload();
  await page.getByLabel("Session token").fill(ownerToken);
  await page.getByRole("button", { name: "Sign in", exact: true }).click();
  await page.getByRole("navigation", { name: "Workspace navigation" }).getByRole("button", { name: "Team & settings", exact: true }).click();
  await panel.getByLabel("Dataset to manage").selectOption(did);
  await panel.getByRole("radio", { name: "Workspace access", exact: false }).check();
  const concurrent = await page.request.put(path, { headers: owner, data: { expected_version: 1, enabled: true, grants: saved.grants } });
  expect(concurrent.ok()).toBe(true);
  await panel.getByRole("button", { name: "Save access rules", exact: true }).click();
  await expect(panel.getByRole("alert")).toContainText("Someone changed access");
  await expect(panel.getByRole("radio", { name: "Workspace access", exact: false })).toBeChecked();
  await panel.getByRole("button", { name: "Reload saved rules", exact: true }).click();
  await expect(panel.getByRole("radio", { name: "Choose each person’s access", exact: false })).toBeChecked();
  const folder = `../../data/verification/2026-10-16/dataset-access/browser-${Date.now()}`;
  mkdirSync(folder, { recursive: true });
  for (const width of [1440, 390, 320]) {
    await page.setViewportSize({ width, height: 1000 });
    await page.emulateMedia({ reducedMotion: "reduce" });
    await panel.scrollIntoViewIfNeeded();
    expect(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth + 1)).toBe(true);
    await panel.screenshot({ path: `${folder}/access-${width}.png`, animations: "disabled" });
  }
  await panel.getByRole("radio", { name: "Workspace access", exact: false }).check();
  await panel.getByRole("button", { name: "Save access rules", exact: true }).click();
  await expect(panel.getByRole("status")).toContainText("Access saved");
  expect((await page.request.get(profilePath, { headers: owner })).ok()).toBe(true);
  expect(errors).toEqual([]);
});
