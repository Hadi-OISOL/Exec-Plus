"""Use case: Declares atomic source-registration and import metadata operations.

What it does: Shares a workspace transaction with final snapshot publication while
keeping external source connections outside local database locks.
"""

from typing import Protocol
from uuid import UUID

from execplus.domain.source_imports import RegisteredSource, SourceImport


class SourceMetadataRepository(Protocol):
    def registered_sources(self, workspace_id: UUID) -> tuple[RegisteredSource, ...]: ...
    def registered_source(
        self, workspace_id: UUID, source_id: UUID, version: int | None = None
    ) -> RegisteredSource: ...
    def add_registered_source(self, value: RegisteredSource) -> None: ...
    def source_import_request(
        self, workspace_id: UUID, actor_id: UUID, request_id: UUID
    ) -> SourceImport | None: ...
    def source_import(
        self, workspace_id: UUID, actor_id: UUID, import_id: UUID
    ) -> SourceImport: ...
    def source_imports(
        self, workspace_id: UUID, actor_id: UUID, dataset_id: UUID
    ) -> tuple[SourceImport, ...]: ...
    def active_source_import_count(self, workspace_id: UUID) -> int: ...
    def pending_source_imports(self, workspace_id: UUID) -> tuple[SourceImport, ...]: ...
    def source_import_for_recovery(self, workspace_id: UUID, import_id: UUID) -> SourceImport: ...
    def add_source_import(self, value: SourceImport) -> None: ...
    def complete_source_import(self, value: SourceImport) -> None: ...
